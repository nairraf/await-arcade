#!/usr/bin/env node
import { spawnSync } from "node:child_process"
import { cpSync, existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import type { GameMeta, Replay, VerifierEntry } from "../../../packages/contract/src/index"
import { verifyReplay } from "../../../packages/framework/src/verify"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "../../..")
const gamesDir = path.join(root, "games")
const shellDir = path.join(root, "packages/shell/src")
const serverDir = path.join(root, "packages/server/src")
const shellRegistry = path.join(shellDir, "registry.generated.ts")
const serverRegistry = path.join(serverDir, "registry.generated.ts")
const templateDir = path.join(root, "skills/await-arcade-game/templates/game")

interface GameConfig {
  readonly meta: GameMeta
  readonly metaPath: string
  readonly core: string
  readonly view: string
}

interface FoundGame {
  readonly dir: string
  readonly dirName: string
  readonly configPath: string
  readonly config: GameConfig
}

function loadConfig(configPath: string): Promise<GameConfig> {
  return import(`${pathToFileURL(configPath).href}?t=${Date.now()}`).then(
    (module) => module.default as GameConfig,
  )
}

async function findGames(): Promise<FoundGame[]> {
  if (!existsSync(gamesDir)) return []

  const found: FoundGame[] = []
  for (const entry of readdirSync(gamesDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const dir = path.join(gamesDir, entry.name)
    const configPath = path.join(dir, "arcade.config.ts")
    if (!existsSync(configPath)) continue

    found.push({
      dir,
      dirName: entry.name,
      configPath,
      config: await loadConfig(configPath),
    })
  }

  return found.sort((left, right) => left.config.meta.id.localeCompare(right.config.meta.id))
}

function resolveModule(gameDir: string, specifier: string): string {
  const base = path.resolve(gameDir, specifier)
  const candidates = [base, `${base}.ts`, `${base}.tsx`, `${base}.js`, `${base}.jsx`]
  const found = candidates.find((candidate) => existsSync(candidate) && statSync(candidate).isFile())

  if (!found) throw new Error(`Cannot resolve ${specifier} from ${gameDir}`)
  return found
}

function importPath(fromDir: string, target: string): string {
  let relative = path.relative(fromDir, target).replaceAll("\\", "/")
  relative = relative.replace(/\.(tsx?|jsx?)$/, "")
  if (!relative.startsWith(".")) relative = `./${relative}`
  return relative
}

function header(): string {
  return "// Generated by `npm run aa -- sync`. Do not edit by hand.\n"
}

async function sync(): Promise<void> {
  const games = await findGames()
  if (games.length === 0) throw new Error("No games found")

  const shellImports: string[] = []
  const shellEntries: string[] = []
  const serverImports: string[] = []
  const serverEntries: string[] = []

  games.forEach((game, index) => {
    const metaFile = resolveModule(game.dir, game.config.metaPath)
    const coreFile = resolveModule(game.dir, game.config.core)
    const viewFile = resolveModule(game.dir, game.config.view)

    shellImports.push(
      `import { core as core${index} } from "${importPath(shellDir, coreFile)}"`,
      `import { meta as meta${index} } from "${importPath(shellDir, metaFile)}"`,
      `import { view as view${index} } from "${importPath(shellDir, viewFile)}"`,
    )
    shellEntries.push(`  { meta: meta${index}, core: core${index}, view: view${index} },`)

    serverImports.push(
      `import { core as core${index} } from "${importPath(serverDir, coreFile)}"`,
      `import { meta as meta${index} } from "${importPath(serverDir, metaFile)}"`,
    )
    serverEntries.push(`  [meta${index}.id]: { meta: meta${index}, core: core${index} },`)
  })

  const shell = [
    header(),
    'import type { GameEntry } from "@await-arcade/contract"',
    ...shellImports,
    "",
    "export const games: readonly GameEntry[] = [",
    ...shellEntries,
    "]",
    "",
  ].join("\n")

  const server = [
    header(),
    'import type { VerifierEntry } from "@await-arcade/contract"',
    ...serverImports,
    "",
    "export const verifiers: Record<string, VerifierEntry> = {",
    ...serverEntries,
    "}",
    "",
  ].join("\n")

  writeFileSync(shellRegistry, shell)
  writeFileSync(serverRegistry, server)

  console.log(`Synced ${games.length} game${games.length === 1 ? "" : "s"}:`)
  for (const game of games) {
    console.log(`  ${game.config.meta.id}  (${game.dirName})`)
  }
}

function titleFromId(id: string): string {
  return id
    .split("-")
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join(" ")
}

function replacePlaceholders(node: string, id: string, title: string): void {
  const stat = statSync(node)
  if (stat.isDirectory()) {
    for (const entry of readdirSync(node)) replacePlaceholders(path.join(node, entry), id, title)
    return
  }

  if (!/\.(ts|tsx|js|jsx|md|json|css)$/.test(node)) return

  const content = readFileSync(node, "utf8")
  const next = content.replaceAll("__ID__", id).replaceAll("__TITLE__", title)
  if (next !== content) writeFileSync(node, next)
}

async function newGame(args: string[]): Promise<void> {
  const id = args[0]
  if (!id) throw new Error("Usage: aa new-game <kebab-case-id>")
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error("Game id must be kebab-case, e.g. neon-cycles")

  const target = path.join(gamesDir, id)
  if (existsSync(target)) throw new Error(`Already exists: ${target}`)
  if (!existsSync(templateDir)) throw new Error(`Template missing: ${templateDir}`)

  cpSync(templateDir, target, { recursive: true })
  replacePlaceholders(target, id, titleFromId(id))
  console.log(`Created games/${id}`)
  await sync()
}

async function loadVerifiers(): Promise<Record<string, VerifierEntry>> {
  const module = await import(`${pathToFileURL(serverRegistry).href}?t=${Date.now()}`)
  return module.verifiers as Record<string, VerifierEntry>
}

async function verifyCommand(args: string[]): Promise<void> {
  const json = args.includes("--json")
  const positional = args.filter((value) => !value.startsWith("--"))
  const gameId = positional[0]
  const replayPath = positional[1]
  if (!gameId || !replayPath) throw new Error("Usage: aa verify <game-id> <replay.json> [--json]")

  const verifiers = await loadVerifiers()
  const entry = verifiers[gameId]
  if (!entry) throw new Error(`Unknown game: ${gameId}`)

  const replay = JSON.parse(readFileSync(path.resolve(replayPath), "utf8")) as Replay
  const result = verifyReplay(entry.core, entry.meta, replay)

  if (json) {
    console.log(JSON.stringify(result, null, 2))
  } else if (result.ok && result.score) {
    console.log(`${gameId}: OK`)
    console.log(`  score:   ${result.score.value} (${result.score.type})`)
    console.log(`  ranked:  ${result.score.ranked}`)
    console.log(`  ticks:   ${result.ticks ?? "—"}`)
    console.log(`  elapsed: ${result.elapsedMs ?? "—"}ms`)
  } else {
    console.log(`${gameId}: FAILED`)
    console.log(`  reason: ${result.reason ?? "unknown"}`)
  }

  if (!result.ok) process.exitCode = 1
}

async function check(): Promise<void> {
  const games = await findGames()
  const verifiers = await loadVerifiers()
  const errors: string[] = []
  const fixtures: string[] = []

  const forbidden = [
    { pattern: /\bMath\.random\b/, label: "Math.random" },
    { pattern: /\bDate\.now\b/, label: "Date.now" },
    { pattern: /\bperformance\.now\b/, label: "performance.now" },
    { pattern: /\bwindow\./, label: "window" },
    { pattern: /\bdocument\./, label: "document" },
    { pattern: /\blocalStorage\b/, label: "localStorage" },
    { pattern: /\bfetch\s*\(/, label: "fetch" },
    { pattern: /\beval\s*\(/, label: "eval" },
    { pattern: /\bnew Function\b/, label: "new Function" },
  ]

  for (const game of games) {
    const coreFile = resolveModule(game.dir, game.config.core)
    const source = readFileSync(coreFile, "utf8")

    for (const rule of forbidden) {
      if (rule.pattern.test(source)) {
        errors.push(`${game.config.meta.id}: core uses ${rule.label} (${path.relative(root, coreFile)})`)
      }
    }

    const fixture = path.join(game.dir, "replay.json")
    if (existsSync(fixture)) {
      const replay = JSON.parse(readFileSync(fixture, "utf8")) as Replay
      const entry = verifiers[replay.gameId]
      if (!entry) {
        errors.push(`${game.config.meta.id}: replay references unknown game ${replay.gameId}`)
      } else {
        const result = verifyReplay(entry.core, entry.meta, replay)
        if (!result.ok) errors.push(`${game.config.meta.id}: fixture failed verification: ${result.reason}`)
        else fixtures.push(`${game.config.meta.id}: fixture ok (${result.score?.value})`)
      }
    }
  }

  for (const line of fixtures) console.log(line)

  if (errors.length > 0) {
    console.error("\nAwait Arcade check failed:")
    for (const error of errors) console.error(`  - ${error}`)
    process.exitCode = 1
    return
  }

  console.log(`Await Arcade check passed for ${games.length} game${games.length === 1 ? "" : "s"}.`)
}

async function list(): Promise<void> {
  const games = await findGames()
  for (const game of games) {
    const meta = game.config.meta
    console.log(`${meta.id.padEnd(18)} ${meta.kind.padEnd(9)} ${meta.status.padEnd(12)} ${meta.title}`)
    console.log(`  modes: ${meta.modes.map((mode) => mode.id).join(", ")}`)
  }
}

function runNpm(script: string): number {
  const result = spawnSync("npm", ["run", script], { cwd: root, stdio: "inherit" })
  return result.status ?? 1
}

async function main(): Promise<void> {
  const [command, ...args] = process.argv.slice(2)

  switch (command) {
    case "sync":
      await sync()
      break
    case "new-game":
      await newGame(args)
      break
    case "verify":
      await verifyCommand(args)
      break
    case "check":
      await check()
      break
    case "list":
      await list()
      break
    case "typecheck":
      process.exitCode = runNpm("typecheck")
      break
    case "test":
      process.exitCode = runNpm("test")
      break
    default:
      console.log(`Await Arcade CLI

  aa sync                     regenerate shell + server registries
  aa new-game <id>            scaffold a new game from the skill template
  aa verify <id> <replay>     verify a replay against the shared core
  aa check                    scan cores and verify replay fixtures
  aa list                     list games
  aa typecheck                run the workspace typecheck
  aa test                     run the workspace tests
`)
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exitCode = 1
})
